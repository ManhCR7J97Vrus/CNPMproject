CREATE TABLE vehicles (
    vehicle_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(255) NOT NULL,
    carrier_name VARCHAR(255) NOT NULL,
    plate_number VARCHAR(255) NOT NULL,
    is_active BOOLEAN NOT NULL,
    UNIQUE (carrier_name, code)
);

CREATE TABLE shipments (
    shipment_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    carrier_name VARCHAR(255) NOT NULL,
    outbound_order_id BIGINT NOT NULL UNIQUE,
    driver_name VARCHAR(255),
    driver_phone VARCHAR(255),
    driver_id BIGINT,
    tracking_no VARCHAR(255),
    status VARCHAR(255) NOT NULL,
    dispatched_at TIMESTAMP(6),
    delivered_at TIMESTAMP(6),
    checked_packages INT,
    checked_at TIMESTAMP(6),
    vehicle_id BIGINT,
    pickup_location VARCHAR(255) NOT NULL,
    dropoff_location VARCHAR(255) NOT NULL,
    contact_name VARCHAR(255),
    contact_phone VARCHAR(255),
    start_at TIMESTAMP(6),
    end_at TIMESTAMP(6),
    received_packages INT,
    delivery_note VARCHAR(255),
    return_requested BOOLEAN NOT NULL DEFAULT FALSE,
    FOREIGN KEY (outbound_order_id) REFERENCES outbound_orders(outbound_order_id),
    FOREIGN KEY (driver_id) REFERENCES users(user_id),
    FOREIGN KEY (vehicle_id) REFERENCES vehicles(vehicle_id),
    CHECK (start_at IS NULL OR end_at > start_at),
    CHECK (checked_packages IS NULL OR checked_packages > 0),
    CHECK (received_packages IS NULL OR received_packages > 0)
);

CREATE TABLE stocktakes (
    stocktake_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reference_no VARCHAR(255) NOT NULL UNIQUE,
    scope_batch_id BIGINT,
    status VARCHAR(255) NOT NULL,
    created_by BIGINT NOT NULL,
    counter_id BIGINT NOT NULL,
    snapshot_at TIMESTAMP(6) NOT NULL,
    reason VARCHAR(255),
    approved_by BIGINT,
    approved_at TIMESTAMP(6),
    FOREIGN KEY (scope_batch_id) REFERENCES batches(batch_id),
    FOREIGN KEY (created_by) REFERENCES users(user_id),
    FOREIGN KEY (counter_id) REFERENCES users(user_id),
    FOREIGN KEY (approved_by) REFERENCES users(user_id)
);

CREATE TABLE stocktake_locations (
    stocktake_id BIGINT NOT NULL,
    location_id BIGINT NOT NULL,
    PRIMARY KEY (stocktake_id, location_id),
    FOREIGN KEY (stocktake_id) REFERENCES stocktakes(stocktake_id),
    FOREIGN KEY (location_id) REFERENCES locations(location_id)
);

CREATE TABLE stocktake_lines (
    line_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    stocktake_id BIGINT NOT NULL,
    inventory_id BIGINT NOT NULL,
    expected_qty DECIMAL(18,3) NOT NULL,
    counted_qty DECIMAL(18,3),
    stock_revision BIGINT NOT NULL,
    reason VARCHAR(255),
    UNIQUE (stocktake_id, inventory_id),
    FOREIGN KEY (stocktake_id) REFERENCES stocktakes(stocktake_id),
    FOREIGN KEY (inventory_id) REFERENCES inventory(inventory_id),
    CHECK (expected_qty >= 0 AND (counted_qty IS NULL OR counted_qty >= 0))
);

CREATE TABLE quarantine_requests (
