CREATE TABLE storage_profiles (
    code VARCHAR(255) PRIMARY KEY,
    temperature_min DECIMAL(6,2),
    temperature_max DECIMAL(6,2),
    humidity_min DECIMAL(5,2),
    humidity_max DECIMAL(5,2),
    avoid_light BOOLEAN NOT NULL,
    fire_protection BOOLEAN NOT NULL,
    incompatible_groups VARCHAR(255) NOT NULL
);

CREATE TABLE service_levels (
    priority VARCHAR(255) PRIMARY KEY,
    sort_rank INT NOT NULL,
    CHECK (sort_rank > 0)
);

CREATE TABLE suppliers (
    supplier_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    supplier_code VARCHAR(255) NOT NULL UNIQUE,
    name VARCHAR(255) NOT NULL,
    phone VARCHAR(255),
    address VARCHAR(255),
    license_no VARCHAR(255),
    is_active BOOLEAN NOT NULL
);

CREATE TABLE users (
    user_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(255) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    full_name VARCHAR(255) NOT NULL,
    email VARCHAR(255),
    phone VARCHAR(255),
    role VARCHAR(255) NOT NULL,
    is_active BOOLEAN NOT NULL,
    created_at TIMESTAMP(6) NOT NULL,
    addr VARCHAR(255),
    supplier_id BIGINT,
    carrier_name VARCHAR(255),
    driver_available BOOLEAN NOT NULL DEFAULT TRUE,
    FOREIGN KEY (supplier_id) REFERENCES suppliers(supplier_id)
);

CREATE TABLE products (
    product_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sku_code VARCHAR(255) NOT NULL UNIQUE,
    name VARCHAR(255) NOT NULL,
    category VARCHAR(255) NOT NULL,
    unit VARCHAR(255) NOT NULL,
    has_expiry BOOLEAN NOT NULL,
    expiry_alert_days INT NOT NULL,
    is_active BOOLEAN NOT NULL,
    storage_condition VARCHAR(255),
    min_stock DECIMAL(18,3) NOT NULL,
    perishable BOOLEAN NOT NULL,
    isolation_group VARCHAR(255),
    FOREIGN KEY (storage_condition) REFERENCES storage_profiles(code),
    CHECK (expiry_alert_days >= 0 AND min_stock >= 0)
);

CREATE TABLE locations (
    location_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(255) NOT NULL,
    warehouse_name VARCHAR(255) NOT NULL,
    zone_name VARCHAR(255) NOT NULL,
    rack_code VARCHAR(255),
    storage_condition VARCHAR(255),
    is_quarantine BOOLEAN NOT NULL,
    is_locked BOOLEAN NOT NULL,
    is_active BOOLEAN NOT NULL,
    UNIQUE (warehouse_name, code),
    FOREIGN KEY (storage_condition) REFERENCES storage_profiles(code)
);

CREATE TABLE batches (
    batch_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id BIGINT NOT NULL,
    supplier_id BIGINT NOT NULL,
    batch_no VARCHAR(255) NOT NULL,
    storage_condition VARCHAR(255),
    mfg_date DATE,
    expiry_date DATE,
    received_at TIMESTAMP(6),
    status VARCHAR(255) NOT NULL,
    UNIQUE (product_id, batch_no),
    FOREIGN KEY (storage_condition) REFERENCES storage_profiles(code),
    FOREIGN KEY (product_id) REFERENCES products(product_id),
    FOREIGN KEY (supplier_id) REFERENCES suppliers(supplier_id),
    CHECK (expiry_date IS NULL OR mfg_date IS NULL OR expiry_date >= mfg_date)
);

CREATE TABLE inventory (
    inventory_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    batch_id BIGINT NOT NULL,
    location_id BIGINT NOT NULL,
    qty_on_hand DECIMAL(18,3) NOT NULL,
    qty_reserved DECIMAL(18,3) NOT NULL,
    updated_at TIMESTAMP(6) NOT NULL,
    stock_revision BIGINT NOT NULL DEFAULT 0,
    UNIQUE (batch_id, location_id),
    FOREIGN KEY (batch_id) REFERENCES batches(batch_id),
    FOREIGN KEY (location_id) REFERENCES locations(location_id),
    CHECK (qty_on_hand >= 0 AND qty_reserved >= 0 AND qty_reserved <= qty_on_hand)
);

CREATE TABLE inventory_movements (
    movement_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    batch_id BIGINT NOT NULL,
    from_location_id BIGINT,
    to_location_id BIGINT,
    movement_type VARCHAR(255) NOT NULL,
    reference_no VARCHAR(255) NOT NULL,
    change_qty DECIMAL(18,3) NOT NULL,
    created_by BIGINT NOT NULL,
    created_at TIMESTAMP(6) NOT NULL,
    reason VARCHAR(255),
    FOREIGN KEY (batch_id) REFERENCES batches(batch_id),
    FOREIGN KEY (from_location_id) REFERENCES locations(location_id),
    FOREIGN KEY (to_location_id) REFERENCES locations(location_id),
    FOREIGN KEY (created_by) REFERENCES users(user_id)
);

CREATE TABLE inbound_orders (
    inbound_order_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    supplier_id BIGINT,
    order_no VARCHAR(255) NOT NULL UNIQUE,
    status VARCHAR(255) NOT NULL,
    expected_at TIMESTAMP(6),
    external_reference VARCHAR(255),
    supplier_notice BOOLEAN NOT NULL DEFAULT FALSE,
    return_of_id BIGINT,
    created_by BIGINT NOT NULL,
    created_at TIMESTAMP(6) NOT NULL,
    UNIQUE (supplier_id, external_reference),
    FOREIGN KEY (supplier_id) REFERENCES suppliers(supplier_id),
    FOREIGN KEY (created_by) REFERENCES users(user_id)
);

CREATE TABLE inbound_items (
    inbound_item_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    inbound_order_id BIGINT NOT NULL,
    product_id BIGINT NOT NULL,
    batch_id BIGINT,
    location_id BIGINT,
    qty_ordered DECIMAL(18,3) NOT NULL,
    qty_received DECIMAL(18,3) NOT NULL,
    qty_accepted DECIMAL(18,3) NOT NULL,
    unit_cost DECIMAL(18,3) NOT NULL,
    item_condition VARCHAR(255),
    proposed_batch_no VARCHAR(255),
    mfg_date DATE,
    expiry_date DATE,
    storage_condition VARCHAR(255),
    discrepancy_reason VARCHAR(255),
    return_item_id BIGINT,
    FOREIGN KEY (inbound_order_id) REFERENCES inbound_orders(inbound_order_id),
    FOREIGN KEY (product_id) REFERENCES products(product_id),
    FOREIGN KEY (batch_id) REFERENCES batches(batch_id),
    FOREIGN KEY (location_id) REFERENCES locations(location_id),
    FOREIGN KEY (storage_condition) REFERENCES storage_profiles(code),
    CHECK (qty_ordered > 0 AND qty_received >= 0 AND qty_accepted BETWEEN 0 AND qty_received AND unit_cost >= 0)
);

CREATE TABLE outbound_orders (
    outbound_order_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id BIGINT NOT NULL,
    order_no VARCHAR(255) NOT NULL UNIQUE,
    priority VARCHAR(255) NOT NULL,
    delivery_deadline TIMESTAMP(6),
    status VARCHAR(255) NOT NULL,
    shipping_address VARCHAR(255) NOT NULL,
    created_by BIGINT NOT NULL,
    created_at TIMESTAMP(6) NOT NULL,
    receiver_name VARCHAR(255),
    receiver_phone VARCHAR(255),
    package_count INT,
    dispatch_no VARCHAR(255) UNIQUE,
    issued_at TIMESTAMP(6),
    cancel_reason VARCHAR(255),
    cancel_request_reason VARCHAR(255),
    cancel_requested_at TIMESTAMP(6),
    FOREIGN KEY (customer_id) REFERENCES users(user_id),
    FOREIGN KEY (created_by) REFERENCES users(user_id),
    FOREIGN KEY (priority) REFERENCES service_levels(priority),
    CHECK (package_count IS NULL OR package_count > 0)
);

CREATE TABLE outbound_items (
    outbound_item_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    outbound_order_id BIGINT NOT NULL,
    product_id BIGINT NOT NULL,
    inventory_id BIGINT,
    qty_requested DECIMAL(18,3) NOT NULL,
    qty_picked DECIMAL(18,3) NOT NULL,
    unit_price DECIMAL(18,3) NOT NULL,
    FOREIGN KEY (outbound_order_id) REFERENCES outbound_orders(outbound_order_id),
    FOREIGN KEY (product_id) REFERENCES products(product_id),
    FOREIGN KEY (inventory_id) REFERENCES inventory(inventory_id),
    CHECK (qty_requested > 0 AND qty_picked BETWEEN 0 AND qty_requested AND unit_price >= 0)
);

